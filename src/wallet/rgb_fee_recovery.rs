//! Explicit self-payment of one native-proven, assignment-free fee input of an
//! expired ordinary RGB original which never reached its Bitcoin dispatch mark.
//! This never cancels/replays that original or releases any RGB hold. Existing
//! confirmed-conflict reconciliation must prove its later impossibility.
use super::*;

/// A separate bounded approval for a new wallet-owned Bitcoin self-payment.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct RgbFeeRecoveryRequest {
    /// Explicit response version, currently one.
    pub version: u8,
    /// Exact existing ordinary RGB operation (UUIDv4/v7).
    pub operation_id: String,
    /// One original, assignment-free native fee input.
    pub outpoint: String,
    /// Exact miner fee, between one and 1,000 whole sats.
    pub fee_sats: String,
    /// Separate approval deadline, at most 120 seconds into the future.
    pub expires_at: String,
    /// Other caller-owned input holds, excluding only this original/recovery.
    pub excluded_inputs: Vec<String>,
}

/// Public immutable review. The destination is generated by the wallet itself.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct RgbFeeRecoveryPrepared {
    /// Explicit response version, currently one.
    pub version: u8,
    /// Fixed wallet-rgb-fee-recovery discriminator.
    pub kind: String,
    /// Exact new unsigned PSBT; never the old RGB transaction.
    pub psbt: String,
    /// Existing original RGB transaction whose fee input is being recovered.
    pub original_txid: String,
    /// Exact existing ordinary operation.
    pub operation_id: String,
    /// Original assignment-free fee input.
    pub outpoint: String,
    /// Native-verified input value, in whole sats.
    pub input_sats: String,
    /// All input value less the explicit miner fee.
    pub amount_sats: String,
    /// Exact miner fee in whole sats.
    pub fee_sats: String,
    /// Independently verifiable wallet-owned vanilla destination.
    pub destination: String,
}

fn refused() -> Error {
    Error::InvalidPsbt {
        details: "RGB fee-input recovery cannot be verified; retain the original".into(),
    }
}
fn integer(value: &str) -> Result<u64, Error> {
    let n: u64 = value.parse().map_err(|_| refused())?;
    if n.to_string() != value {
        return Err(refused());
    }
    Ok(n)
}
fn now_seconds() -> Result<u64, Error> {
    #[cfg(target_arch = "wasm32")]
    let n = now().unix_timestamp();
    #[cfg(not(target_arch = "wasm32"))]
    let n = time::OffsetDateTime::now_utc().unix_timestamp();
    u64::try_from(n).map_err(|_| refused())
}
fn validate(request: &RgbFeeRecoveryRequest) -> Result<(OutPoint, u64), Error> {
    let now = now_seconds()?;
    let expiry = integer(&request.expires_at)?;
    let fee = integer(&request.fee_sats)?;
    if request.version != 1
        || request.operation_id.len() != 36
        || request.outpoint.len() > 75
        || !(1..=1000).contains(&fee)
        || expiry <= now
        || expiry > now.checked_add(120).ok_or_else(refused)?
        || request.excluded_inputs.len() > 4096
    {
        return Err(refused());
    }
    let point: OutPoint = request.outpoint.parse().map_err(|_| refused())?;
    if point.to_string() != request.outpoint {
        return Err(refused());
    }
    let mut excluded = HashSet::new();
    for value in &request.excluded_inputs {
        let p: OutPoint = value.parse().map_err(|_| refused())?;
        if p.to_string() != *value || !excluded.insert(p) {
            return Err(refused());
        }
    }
    if excluded.contains(&point) {
        return Err(refused());
    }
    Ok((point, fee))
}

impl Wallet {
    fn rgb_fee_recovery_source(
        &self,
        request: &RgbFeeRecoveryRequest,
    ) -> Result<(String, BitcoinSpendInput), Error> {
        validate(request)?;
        if self.bitcoin_network() != BitcoinNetwork::Regtest {
            return Err(Error::InvalidRecipientNetwork);
        }
        let (txid, artifacts) = self
            .wallet_transfer_by_operation(&request.operation_id)?
            .ok_or_else(refused)?;
        let external = artifacts.external_send.as_ref().ok_or_else(refused)?;
        let binding = external.wallet_transfer.as_ref().ok_or_else(refused)?;
        let original: WalletRgbSendRequest =
            serde_json::from_str(&binding.request_json).map_err(|_| refused())?;
        if external.status != ExternalSendStatus::Prepared
            || binding.restored
            || !binding.signing_attempted
            || binding.broadcast_attempted
            || original.operation_id != request.operation_id
            || original.expires_at == 0
            || original.expires_at > now_seconds()?
        {
            return Err(refused());
        }
        let signed = Psbt::from_str(artifacts.signed_psbt.as_ref().ok_or_else(refused)?)
            .map_err(|_| refused())?
            .extract_tx()
            .map_err(|_| refused())?;
        if signed.compute_txid().to_string() != *txid
            || Self::tx_stripped_hex(&signed) != external.expected_tx_hex
            || signed.input.iter().any(|i| {
                i.witness.len() != 1 || i.witness.iter().next().is_none_or(|sig| sig.len() != 64)
            })
        {
            return Err(refused());
        }
        // This checks current BDK ownership/confirmation, every Stock contract,
        // pending receives and every OTHER managed original. Only this exact
        // original's assignment-free fee coins are eligible; never its RGB seals.
        let mut coins = self
            .bitcoin_rgb_fee_inputs(&request.operation_id)?
            .into_iter()
            .filter(|coin| coin.outpoint == request.outpoint);
        let coin = coins.next().ok_or_else(refused)?;
        if coins.next().is_some() {
            return Err(refused());
        }
        Ok((txid.clone(), coin))
    }

    pub(super) fn checked_rgb_fee_recovery_psbt(
        &self,
        request: &RgbFeeRecoveryRequest,
        encoded: &str,
        signed: bool,
    ) -> Result<Psbt, Error> {
        let (point, fee) = validate(request)?;
        let (original, coin) = self.rgb_fee_recovery_source(request)?;
        if encoded.is_empty() || encoded.len() > 180_000 {
            return Err(refused());
        }
        let psbt = Psbt::from_str(encoded).map_err(|_| refused())?;
        if psbt.inputs.len() != 1
            || psbt.unsigned_tx.input.len() != 1
            || psbt.unsigned_tx.output.len() != 1
            || psbt.unsigned_tx.input[0].previous_output != point
            || psbt.unsigned_tx.compute_txid().to_string() == original
        {
            return Err(refused());
        }
        let input = &psbt.inputs[0];
        if input.sighash_type.is_some_and(|kind| kind.to_u32() != 0) {
            return Err(refused());
        }
        let witness = input.witness_utxo.as_ref().ok_or_else(refused)?;
        let output = &psbt.unsigned_tx.output[0];
        let amount = integer(&coin.amount_sats)?
            .checked_sub(fee)
            .ok_or_else(refused)?;
        if witness.value.to_sat().to_string() != coin.amount_sats
            || witness.script_pubkey.to_hex_string() != coin.script_hex
            || output.value.to_sat() != amount
            || output.value < TxOut::minimal_non_dust(output.script_pubkey.clone()).value
            || !output.script_pubkey.is_p2tr()
            || !matches!(
                self.bdk_wallet
                    .derivation_of_spk(output.script_pubkey.clone()),
                Some((KeychainKind::Internal, _))
            )
        {
            return Err(refused());
        }
        if !signed
            && (input.tap_key_sig.is_some()
                || input.final_script_witness.is_some()
                || input.final_script_sig.is_some()
                || !input.partial_sigs.is_empty()
                || !input.tap_script_sigs.is_empty())
        {
            return Err(refused());
        }
        if signed {
            let tx = psbt.clone().extract_tx().map_err(|_| refused())?;
            if tx.input[0].witness.len() != 1
                || tx.input[0]
                    .witness
                    .iter()
                    .next()
                    .is_none_or(|sig| sig.len() != 64)
            {
                return Err(refused());
            }
        }
        Ok(psbt)
    }

    pub(super) fn build_rgb_fee_recovery(
        &mut self,
        request: &RgbFeeRecoveryRequest,
    ) -> Result<RgbFeeRecoveryPrepared, Error> {
        let (point, fee) = validate(request)?;
        let (original_txid, coin) = self.rgb_fee_recovery_source(request)?;
        let amount = integer(&coin.amount_sats)?
            .checked_sub(fee)
            .ok_or_else(refused)?;
        let destination = self._get_new_address(KeychainKind::Internal)?;
        let mut builder = self.bdk_wallet.build_tx();
        builder
            .add_utxo(point)
            .map_err(|_| refused())?
            .manually_selected_only()
            .add_recipient(destination.script_pubkey(), BdkAmount::from_sat(amount))
            .fee_absolute(BdkAmount::from_sat(fee));
        let psbt = builder.finish().map_err(|_| refused())?.to_string();
        self.checked_rgb_fee_recovery_psbt(request, &psbt, false)?;
        self.bdk_wallet.persist(&mut self.bdk_database)?;
        Ok(RgbFeeRecoveryPrepared {
            version: 1,
            kind: "wallet-rgb-fee-recovery".into(),
            psbt,
            original_txid,
            operation_id: request.operation_id.clone(),
            outpoint: point.to_string(),
            input_sats: coin.amount_sats,
            amount_sats: amount.to_string(),
            fee_sats: fee.to_string(),
            destination: destination.to_string(),
        })
    }

    async fn rgb_fee_recovery_online(
        &mut self,
        online: Online,
        request: &RgbFeeRecoveryRequest,
    ) -> Result<(), Error> {
        validate(request)?;
        self.require_wallet_rgb_regtest(&online).await?;
        self.sync_db_txos(false).await?;
        let (original, _) = self.rgb_fee_recovery_source(request)?;
        if self
            .indexer()
            .get_tx_with_status(&original.parse().map_err(|_| refused())?)
            .await?
            .is_some()
        {
            return Err(refused());
        }
        validate(request)?;
        Ok(())
    }

    /// Prepare a separate self-payment. No old approval/expiry is modified, no
    /// signature is requested, and no original or RGB hold is retired.
    pub async fn prepare_rgb_fee_recovery(
        &mut self,
        online: Online,
        request: RgbFeeRecoveryRequest,
    ) -> Result<RgbFeeRecoveryPrepared, Error> {
        self.rgb_fee_recovery_online(online, &request).await?;
        let result = self.build_rgb_fee_recovery(&request)?;
        self.flush().await?;
        validate(&request)?;
        Ok(result)
    }

    /// The host MUST persist its new recovery original and all input holds first.
    /// This signs only the exact separately approved self-payment, never the RGB
    /// original. Unknown/restored/dispatched native originals fail closed.
    pub async fn sign_rgb_fee_recovery(
        &mut self,
        online: Online,
        request: RgbFeeRecoveryRequest,
        encoded: String,
    ) -> Result<String, Error> {
        self.rgb_fee_recovery_online(online, &request).await?;
        let mut psbt = self.checked_rgb_fee_recovery_psbt(&request, &encoded, false)?;
        // Commit native sequence before signing: a stale other-tab snapshot is
        // not proof that the original never crossed its dispatch checkpoint.
        self.flush().await?;
        self.checked_rgb_fee_recovery_psbt(&request, &encoded, false)?;
        self._sign_psbt(&mut psbt, None)?;
        let result = psbt.to_string();
        self.checked_rgb_fee_recovery_psbt(&request, &result, true)?;
        Ok(result)
    }

    /// One explicit submission of the NEW self-payment. The caller persists its
    /// signature and dispatch attempt first. Original RGB holds remain until
    /// established confirmed-conflict reconciliation proves their impossibility.
    pub async fn broadcast_rgb_fee_recovery(
        &mut self,
        online: Online,
        request: RgbFeeRecoveryRequest,
        encoded: String,
    ) -> Result<String, Error> {
        self.rgb_fee_recovery_online(online, &request).await?;
        let psbt = self.checked_rgb_fee_recovery_psbt(&request, &encoded, true)?;
        self.flush().await?;
        self.checked_rgb_fee_recovery_psbt(&request, &encoded, true)?;
        let tx = psbt.extract_tx().map_err(|_| refused())?;
        self.indexer().broadcast(&tx).await.map_err(|_| refused())?;
        self.record_broadcast_transaction(tx.clone(), true).await?;
        self.update_backup_info(false)?;
        Ok(tx.compute_txid().to_string())
    }
}

